# 2. DataFrame 변환 및 날짜 Shift 로직 함수
def process_events(date_list, event_type, desc, days_shift=0):
    df = pd.DataFrame({'original_date': date_list})
    df['original_date'] = pd.to_datetime(df['original_date'])
    
    # 핵심: 한국 반영일 = 원본 날짜 + 시차(days_shift)
    df['event_date'] = df['original_date'] + timedelta(days=days_shift)
    
    df['event_type'] = event_type
    df['description'] = desc
    return df

